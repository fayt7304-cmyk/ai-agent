export function isRtl(lang: Lang): boolean {
  return RTL_LANGS.includes(lang);
}

export function getStoredLang(): Lang {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored && stored in translations) return stored as Lang;
  // Fall back to the browser's language if it's one we support, otherwise English.
  const browserLang = (navigator.language || "en").slice(0, 2).toLowerCase();
  return (Object.keys(translations) as Lang[]).includes(browserLang as Lang) ? (browserLang as Lang) : "en";
}

/** Translate a key for the currently-applied language, falling back to English. */
export function t(key: string): string {
  const lang = document.documentElement.getAttribute("data-lang") as Lang | null;
  const table = (lang && translations[lang]) || translations.en;
  return table[key] ?? translations.en[key] ?? key;
}

function applyTranslations(lang: Lang) {
  const table = translations[lang];
  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key && table[key]) el.textContent = table[key];
  });
  document.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key && table[key]) el.placeholder = table[key];
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key && table[key]) el.title = table[key];
  });
}

/** Apply + persist a language choice. */
export function setLang(lang: Lang) {
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.setAttribute("data-lang", lang);
  document.documentElement.setAttribute("lang", lang);
  document.documentElement.setAttribute("dir", isRtl(lang) ? "rtl" : "ltr");
  applyTranslations(lang);
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

/** Call once on startup, as early as possible, so there's no flash of the wrong language/direction. */
export function initI18n() {
  setLang(getStoredLang());
}
